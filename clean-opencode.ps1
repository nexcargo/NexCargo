#!/usr/bin/env pwsh

Write-Host "Starting OpenCode context sanitizer..." -ForegroundColor Cyan

# 1. Project-level temp graveyards
Write-Host "Removing project build/cache artifacts..." -ForegroundColor Yellow
$foldersToRemove = @(
    ".\dist", ".\build", ".\out", ".\.next", ".\node_modules\.cache",
    ".\__pycache__", ".\target"
)
foreach ($folder in $foldersToRemove) {
    if (Test-Path $folder) {
        Remove-Item -Recurse -Force $folder -ErrorAction SilentlyContinue
        Write-Host "  Removed: $folder"
    }
}

# Remove all *.egg-info directories recursively
Get-ChildItem -Recurse -Directory -Filter "*.egg-info" | ForEach-Object {
    Remove-Item -Recurse -Force $_.FullName -ErrorAction SilentlyContinue
    Write-Host "  Removed: $($_.FullName)"
}

# Remove large log files (>1MB)
Get-ChildItem -Recurse -File -Filter "*.log" | Where-Object { $_.Length -gt 1MB } | ForEach-Object {
    Remove-Item -Force $_.FullName -ErrorAction SilentlyContinue
    Write-Host "  Removed large log: $($_.Name)"
}

# 2. User temp files (safe to delete)
Write-Host "Cleaning user temporary directories..." -ForegroundColor Yellow
$userTemp = "$env:USERPROFILE\tmp"
if (Test-Path $userTemp) {
    Remove-Item -Recurse -Force "$userTemp\*" -ErrorAction SilentlyContinue
}
$opencodeCache = "$env:USERPROFILE\.cache\opencode\sessions"
if (Test-Path $opencodeCache) {
    Write-Host "Clearing old OpenCode sessions (older than 1 day)..." -ForegroundColor Yellow
    Get-ChildItem $opencodeCache -File | Where-Object { $_.LastWriteTime -lt (Get-Date).AddDays(-1) } | Remove-Item -Force -ErrorAction SilentlyContinue
}

# 3. Critical: Update .opencodeignore
$ignoreFile = ".opencodeignore"
if (-not (Test-Path $ignoreFile)) {
    Write-Host "Creating .opencodeignore..." -ForegroundColor Yellow
    @"
# Auto-generated by clean-opencode.ps1
node_modules/
.git/
dist/
build/
*.log
*.tmp
.cache/
__pycache__/
.env
*.lock
"@ | Out-File -FilePath $ignoreFile -Encoding utf8
} else {
    Write-Host "Updating .opencodeignore..." -ForegroundColor Yellow
    $content = Get-Content $ignoreFile -Raw
    $linesToAdd = @("*.tmp", ".cache/")
    foreach ($line in $linesToAdd) {
        if ($content -notmatch [regex]::Escape($line)) {
            Add-Content -Path $ignoreFile -Value $line -Encoding utf8
            Write-Host "  Added: $line"
        }
    }
}

# 4. Show estimated size (exclude node_modules and .git)
Write-Host "`nContext cleanup complete!" -ForegroundColor Green
$size = Get-ChildItem . -Exclude node_modules,.git -Recurse -File | Measure-Object -Property Length -Sum
if ($size.Count -gt 0) {
    $sizeInMB = [math]::Round($size.Sum / 1MB, 2)
    Write-Host "Estimated project size (excluding node_modules and .git): $sizeInMB MB"
} else {
    Write-Host "Project is very small or empty."
}